import { fireEvent } from "@testing-library/react";

// Локальный тест-хелпер (замороженный `setup.ts` не тронут): единственная точка,
// через которую тест отдаёт композеру выбранные файлы.
//
// Пользователь выбирает файлы системным диалогом: жмёт «Прикрепить файл», и
// браузер открывает окно ОС поверх страницы. В jsdom этого окна нет —
// `input.click()` не делает ничего, и подставить выбор можно только событием
// `change` на самом `<input type="file">`. Сам input скрыт (`hidden`), роли у
// него нет и доступного имени тоже — ни `getByRole`, ни `getByLabelText` до
// него не достают, поэтому остаётся структурный селектор.
//
// `conventions/testing.md` § Frontend запрещает `container.querySelector` в
// теле кейса — и правильно: там он привязывает ассерты к разметке. Здесь
// селектор ровно один на весь набор, спрятан за именем действия и не участвует
// ни в одном ассерте: кейсы читают результат по видимому чипу. Дублировать его
// по суитам нельзя (§ общие тест-утилиты не дублируются) — отсюда общий модуль.
/**
 * Отдаёт композеру внутри `container` выбранные файлы — эквивалент выбора в
 * системном диалоге по кнопке «Прикрепить файл».
 */
export function attachFiles(container: HTMLElement, ...files: File[]): void {
  const input = container.querySelector<HTMLInputElement>('input[type="file"]');
  if (input === null) {
    throw new Error("Скрытого `input[type=file]` в композере нет");
  }
  fireEvent.change(input, { target: { files } });
}
