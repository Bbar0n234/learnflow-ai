import type { AuthProvider } from "@/shared/ui/ProviderButton";

/**
 * Неразрывный пробел (U+00A0) — экранированной последовательностью, а не
 * символом: в литерале он глазом неотличим от обычного пробела, а разница
 * наблюдаема — `getByRole` доступное имя не нормализует, и подмена символа
 * красит запросы обеих суит.
 */
export const NBSP = "\u00A0";

/**
 * Эталонные подписи кнопок провайдеров — **одна копия на весь набор**.
 *
 * Копий было две (своя в суите `ProviderButton` и своя в суите
 * `LoginScreenView`), и одна прод-правка подписи Яндекса покрасила шесть кейсов
 * в двух файлах разом. Подписи — общий контракт: кнопку рисует `shared/ui`, а
 * ищут её по доступному имени обе суиты, — поэтому живут они в одном месте.
 *
 * Копия именно **своя**, а не импорт `DEFAULT_LABELS` из компонента: тест,
 * сверяющий прод сам с собой, зелен при любой подписи. Здесь записано то, что
 * требует мокап, — включая неразрывный пробел между «Яндекс» и «ID»
 * (`Войти с Яндекс&nbsp;ID`): ниже `lg` карточка тянется во всю ширину, и с
 * обычным пробелом «ID» уезжает на вторую строку в отрыве от названия.
 *
 * Тип `Record<AuthProvider, string>` — сторож состава союза, и работает он
 * `tsc`, а не рантайм-ассертом: тест-файлы типизируются вместе с продом
 * (`tsconfig.app.json` включает весь `src`), поэтому четвёртый провайдер (в том
 * числе возвращённый VK ID, снятый решением архитектора по 149-ФЗ) роняет
 * `make check-fe` на недостающем ключе, а исчезнувший третий — на лишнем.
 */
export const PROVIDER_LABELS: Record<AuthProvider, string> = {
  yandex: `Войти с Яндекс${NBSP}ID`,
  google: "Войти через Google",
  github: "Войти через GitHub",
};
